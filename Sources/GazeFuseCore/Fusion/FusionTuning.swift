// FusionTuning.swift — the set of fusion/arbiter parameters the benchmark tuner may
// vary, with their search ranges, plus the generator for DefaultTuning.swift.
import Foundation

/// Everything that runs in the cursor pipeline, as one Codable document
/// (`docs/tuned-fusion-config.json`).
public struct FusionTuningBundle: Codable, Equatable {
    public var fusion: EKFCursorFusionConfig
    public var arbiter: ClickArbiterConfig
    public var direct: DirectGazeCursorConfig

    public init(fusion: EKFCursorFusionConfig = EKFCursorFusionConfig(),
                arbiter: ClickArbiterConfig = ClickArbiterConfig(),
                direct: DirectGazeCursorConfig = DirectGazeCursorConfig()) {
        self.fusion = fusion; self.arbiter = arbiter; self.direct = direct
    }
}

public struct FusionTunable {
    public let name: String
    public let range: ClosedRange<Double>
    /// Search in log space (for scale-like parameters).
    public let logScale: Bool
    /// Round to an integer before applying.
    public let integer: Bool
    public let get: (FusionTuningBundle) -> Double
    public let set: (inout FusionTuningBundle, Double) -> Void

    public init(_ name: String, _ range: ClosedRange<Double>, log: Bool = false, integer: Bool = false,
                _ keyPath: WritableKeyPath<FusionTuningBundle, Double>) {
        self.name = name; self.range = range; logScale = log; self.integer = integer
        get = { $0[keyPath: keyPath] }
        set = { $0[keyPath: keyPath] = $1 }
    }

    public init(_ name: String, _ range: ClosedRange<Double>, log: Bool = false, integer: Bool = false,
                get: @escaping (FusionTuningBundle) -> Double, set: @escaping (inout FusionTuningBundle, Double) -> Void) {
        self.name = name; self.range = range; logScale = log; self.integer = integer; self.get = get; self.set = set
    }

    public func clamp(_ v: Double) -> Double {
        let c = min(max(v, range.lowerBound), range.upperBound)
        return integer ? c.rounded() : c
    }
}

public enum FusionTunables {
    /// Parameters searched by `gazefuse-bench tune`. Names match DefaultTuning.swift.
    public static let all: [FusionTunable] = [
        FusionTunable("gazeSigmaPoints", 8...90, log: true, \.fusion.gazeSigmaPoints),
        FusionTunable("positionProcessSigma", 0.3...60, log: true, \.fusion.positionProcessSigma),
        FusionTunable("biasProcessSigma", 0.1...40, log: true, \.fusion.biasProcessSigma),
        FusionTunable("biasPriorSigma", 10...150, log: true, \.fusion.biasPriorSigma),
        FusionTunable("biasCorrelationLength", 50...5000, log: true, \.fusion.biasCorrelationLength),
        FusionTunable("saccadeGateNIS", 4...30, log: true, \.fusion.saccadeGateNIS),
        FusionTunable("saccadeWindowGateNIS", 8...60, log: true, \.fusion.saccadeWindowGateNIS),
        FusionTunable("saccadeMinJumpPoints", 10...120, log: true, \.fusion.saccadeMinJumpPoints),
        FusionTunable("saccadeConfirmSamples", 1...3, integer: true,
                      get: { Double($0.fusion.saccadeConfirmSamples) },
                      set: { $0.fusion.saccadeConfirmSamples = Int($1.rounded()) }),
        FusionTunable("saccadeClusterSigmas", 1.5...6, \.fusion.saccadeClusterSigmas),
        FusionTunable("headAccelerationSigma", 500...30000, log: true, \.fusion.headAccelerationSigma),
        FusionTunable("headDeadbandRadPerSec", 0.002...0.08, log: true, \.fusion.head.deadbandRadPerSec),
        FusionTunable("headPointsPerRadian", 300...6000, log: true, \.fusion.head.pointsPerRadian),
        FusionTunable("headAccelExponent", 0...1.2, \.fusion.head.accelExponent),
        FusionTunable("headVelocitySigma", 1...200, log: true, \.fusion.head.velocitySigma),
        FusionTunable("onsetLookback", 0...0.25, \.arbiter.onsetLookback),
        FusionTunable("directMinCutoff", 0.2...8, log: true, \.direct.oneEuro.minCutoff),
        FusionTunable("directBeta", 0.0005...0.1, log: true, \.direct.oneEuro.beta),
    ]

    public static func tunable(named name: String) -> FusionTunable? { all.first { $0.name == name } }

    /// Full text of Sources/GazeFuseCore/Fusion/DefaultTuning.swift for `bundle`.
    public static func renderDefaultTuningSwift(_ b: FusionTuningBundle, note: String = "") -> String {
        func f(_ v: Double) -> String {
            if v == v.rounded() && abs(v) < 1e9 { return String(format: "%.0f", v) }
            return String(format: "%.6g", v)
        }
        var s = """
        // DefaultTuning.swift — tuned default values of the fusion / arbiter tunables.
        //
        // This file is (re)generated by `gazefuse-bench tune --write-defaults`; edit the
        // ranges in FusionTuning.swift rather than the numbers here. The config structs'
        // initializers use these constants as their default arguments, so the tuned values
        // are what the app gets with `EKFCursorFusionConfig()` / `ClickArbiterConfig()`.
        \(note.isEmpty ? "" : "// " + note + "\n")import Foundation

        public enum FusionDefaultTuning {
            // EKFCursorFusionConfig
            public static let gazeSigmaPoints: Double = \(f(b.fusion.gazeSigmaPoints))
            public static let positionProcessSigma: Double = \(f(b.fusion.positionProcessSigma))
            public static let biasProcessSigma: Double = \(f(b.fusion.biasProcessSigma))
            public static let biasPriorSigma: Double = \(f(b.fusion.biasPriorSigma))
            public static let biasCorrelationLength: Double = \(f(b.fusion.biasCorrelationLength))
            public static let saccadeGateNIS: Double = \(f(b.fusion.saccadeGateNIS))
            public static let saccadeWindowGateNIS: Double = \(f(b.fusion.saccadeWindowGateNIS))
            public static let saccadeMinJumpPoints: Double = \(f(b.fusion.saccadeMinJumpPoints))
            public static let saccadeConfirmSamples: Int = \(b.fusion.saccadeConfirmSamples)
            public static let saccadeClusterSigmas: Double = \(f(b.fusion.saccadeClusterSigmas))
            public static let headAccelerationSigma: Double = \(f(b.fusion.headAccelerationSigma))
            // HeadPointerConfig
            public static let headDeadbandRadPerSec: Double = \(f(b.fusion.head.deadbandRadPerSec))
            public static let headPointsPerRadian: Double = \(f(b.fusion.head.pointsPerRadian))
            public static let headAccelExponent: Double = \(f(b.fusion.head.accelExponent))
            public static let headVelocitySigma: Double = \(f(b.fusion.head.velocitySigma))
            // ClickArbiterConfig
            public static let onsetLookback: Double = \(f(b.arbiter.onsetLookback))
            // DirectGazeCursorConfig
            public static let directMinCutoff: Double = \(f(b.direct.oneEuro.minCutoff))
            public static let directBeta: Double = \(f(b.direct.oneEuro.beta))
        }

        """
        s = s.replacingOccurrences(of: "\n\nimport Foundation", with: "\nimport Foundation")
        return s
    }
}
